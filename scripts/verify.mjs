import fs from 'node:fs';
import assert from 'node:assert/strict';
assert.equal(JSON.parse(fs.readFileSync('wrangler.jsonc','utf8')).name,'pcblarcade');
for(const path of ['site/index.html','site/app.js','site/world-url.js','site/games/attax/index.html','site/games/versus/index.html']) assert(fs.existsSync(path),`Missing ${path}`);
const html=fs.readFileSync('site/index.html','utf8');
const css=fs.readFileSync('site/styles.css','utf8');
for(const feature of ['OPEN WORLD','CUSTOM CAREER','PCBL VERSUS','PCBA PICKUP','HORROR','RACING','MULTIPLAYER']) assert(html.includes(feature),`Missing launch overlay feature: ${feature}`);
assert(html.includes('world-aaa-hero')&&html.includes('world-daytime-wordmark'),'Featured WORLD game image/logo overlay missing');
assert(css.includes('pcbl-world-daytime-camera.png')&&css.includes('world-aaa-hero'),'In-game WORLD screenshot styling missing');
console.log('Arcade files, deployment target, and compact WORLD launch overlay verified.');
